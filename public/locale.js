  const supportedLanguages = ["it", "es", "fr", "de", "en"];
  const storageKey = "papilla-language";
  let language = "it";

  try {
    const saved = window.localStorage.getItem(storageKey);
    if (supportedLanguages.includes(saved)) language = saved;
  } catch {
    // The selected language still works when browser storage is unavailable.
  }

  function t(source, params = {}) {
    const translated = messages[source]?.[language] ?? source;
    return String(translated).replace(/\{(\w+)\}/g, (match, key) =>
      Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : match);
  }

  function translateItem(item, mode) {
    const dictionary = mode === "food" ? window.PAPILLA_FOOD_I18N : window.PAPILLA_DRINKS_I18N;
    const translated = dictionary?.[language]?.[item.id];
    if (!translated) return { ...item };
    const result = {
      ...item,
      name: translated.name ?? item.name,
      description: translated.description ?? item.description
    };
    if (item.unit) result.unit = translated.unit ?? t(item.unit);
    return result;
  }

  // Keep original DOM strings so repeated language changes never translate a translation.
  const textNodes = [];
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.parentElement?.closest("script, style, noscript, #language-select")) continue;
    const raw = node.nodeValue;
    const source = raw.trim().replace(/\s+/g, " ");
    if (!messages[source]) continue;
    textNodes.push({
      node,
      source,
      prefix: raw.match(/^\s*/)[0],
      suffix: raw.match(/\s*$/)[0]
    });
  }

  const attributes = [];
  document.querySelectorAll("[aria-label], [alt], [placeholder], [title]").forEach((node) => {
    for (const name of ["aria-label", "alt", "placeholder", "title"]) {
      const source = node.getAttribute(name);
      if (source && messages[source]) attributes.push({ node, name, source });
    }
  });
  const originalTitle = document.title;
  const description = document.querySelector('meta[name="description"]');
  const originalDescription = description?.getAttribute("content");
  const selector = document.querySelector("#language-select");

  function applyStaticTranslations() {
    document.documentElement.lang = language;
    document.title = t(originalTitle);
    if (description && originalDescription) description.setAttribute("content", t(originalDescription));
    textNodes.forEach(({ node, source, prefix, suffix }) => {
      if (node.isConnected) node.nodeValue = prefix + t(source) + suffix;
    });
    attributes.forEach(({ node, name, source }) => {
      if (node.isConnected) node.setAttribute(name, t(source));
    });
    document.querySelectorAll(".review-card blockquote").forEach((node) => { node.lang = language; });
    if (selector) selector.value = language;
    const currentLanguage = document.querySelector("#language-current");
    if (currentLanguage) currentLanguage.textContent = language.toUpperCase();
  }

  function setLanguage(nextLanguage) {
    if (!supportedLanguages.includes(nextLanguage)) return false;
    language = nextLanguage;
    try {
      window.localStorage.setItem(storageKey, language);
    } catch {
      // Browser storage is optional.
    }
    applyStaticTranslations();
    document.dispatchEvent(new Event("papilla:languagechange"));
    return true;
  }

  window.PapillaLocale = {
    get lang() { return language; },
    t,
    setLanguage,
    translateItem
  };
  selector?.addEventListener("change", (event) => setLanguage(event.target.value));
